import type { Metadata } from "next";
import { routing } from "@/i18n/routing";
import { SITE_URL } from "@/lib/site";

// Open Graph locale codes (language_TERRITORY)
export const OG_LOCALES: Record<string, string> = {
  en: "en_US",
  es: "es_ES",
  "pt-BR": "pt_BR",
  de: "de_DE",
  ja: "ja_JP",
  ar: "ar_AR",
  fr: "fr_FR",
  id: "id_ID",
  ko: "ko_KR",
  hi: "hi_IN",
  tr: "tr_TR",
  vi: "vi_VN",
  "zh-CN": "zh_CN",
  "zh-TW": "zh_TW",
  ru: "ru_RU",
};

// Canonical URL plus hreflang alternates for every locale of the same page
export function localeAlternates(locale: string, path: string) {
  const languages: Record<string, string> = Object.fromEntries(
    routing.locales.map((code) => [code, `${SITE_URL}/${code}${path}`])
  );
  languages["x-default"] = `${SITE_URL}/${routing.defaultLocale}${path}`;

  return {
    canonical: `${SITE_URL}/${locale}${path}`,
    languages,
  };
}

// Generated by `npm run og`; one 1200×630 image per locale and page
export function ogImageUrl(locale: string, page: string) {
  return `${SITE_URL}/og/${locale}/${page}.png`;
}

export function pageMetadata({
  locale,
  path,
  page,
  title,
  description,
  noIndex = false,
}: {
  locale: string;
  path: string;
  page: string;
  title: string;
  description: string;
  noIndex?: boolean;
}): Metadata {
  const image = ogImageUrl(locale, page);
  const shortDescription = truncate(description);

  return {
    title,
    description: shortDescription,
    alternates: localeAlternates(locale, path),
    robots: noIndex ? { index: false, follow: false } : undefined,
    openGraph: {
      type: "website",
      url: `${SITE_URL}/${locale}${path}`,
      siteName: "Doctor Food",
      title,
      description: shortDescription,
      locale: OG_LOCALES[locale],
      alternateLocale: routing.locales
        .filter((code) => code !== locale)
        .map((code) => OG_LOCALES[code]),
      images: [{ url: image, width: 1200, height: 630, alt: title }],
    },
    twitter: {
      card: "summary_large_image",
      title,
      description: shortDescription,
      images: [image],
    },
  };
}

// Keeps descriptions near search-result length, cutting at a word boundary
export function truncate(text: string, max = 155) {
  if (text.length <= max) return text;
  const cut = text.slice(0, max - 1);
  const lastSpace = cut.lastIndexOf(" ");
  return `${(lastSpace > max * 0.6 ? cut.slice(0, lastSpace) : cut).trimEnd()}…`;
}
